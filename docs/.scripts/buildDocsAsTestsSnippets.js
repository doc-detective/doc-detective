// Generates fern/pages/reference/docs-as-tests/examples/<example>/_variants.mdx
// from the example's files (prose.*, detected.*, inline.*, standalone.spec.*)
// in docs-as-tests/examples/<example>/. The sources live outside fern/pages so
// the docs run doesn't pick them up; checkDocsAsTests.js runs them.
// Pages include it with <Markdown src="examples/<example>/_variants.mdx" />.
// The snippets are GENERATED — edit the example files, then run
// `npm run docs:build-docs-as-tests`. `--check` fails if a snippet is stale.
//
// Why not <Code src> per file: Fern 4.15 renders a stray `title=` header on
// those blocks. Inlining titled fenced blocks avoids it, and the example
// files stay the single source that both the page and the test run read.

const fs = require("fs");
const path = require("path");

const examplesDir = path.resolve(__dirname, "../docs-as-tests/examples");
const pagesDir = path.resolve(__dirname, "../fern/pages/reference/docs-as-tests/examples");
const OUTPUT = "_variants.mdx";

const MODES = [
  ["prose", "Prose"],
  ["detected", "Detected"],
  ["inline", "Inline"],
  ["standalone", "Standalone"],
];
// [extension, tab title, fence language], in tab order.
const FORMATS = [
  ["md", "Markdown", "markdown"],
  ["mdx", "MDX", "mdx"],
  ["adoc", "AsciiDoc", "asciidoc"],
  ["html", "HTML", "html"],
  ["rst", "reStructuredText", "rst"],
  ["dita", "DITA", "xml"],
  ["txt", "Plain text", "text"],
  ["json", "JSON", "json"],
  ["yaml", "YAML", "yaml"],
];

function fence(name, language, content) {
  const longestRun = Math.max(0, ...(content.match(/`+/g) || []).map((run) => run.length));
  const ticks = "`".repeat(Math.max(3, longestRun + 1));
  const block = `${ticks}${language} title="${name}"\n${content.replace(/\n$/, "")}\n${ticks}`;
  if (!FERN_INCLUDE.test(block)) return block;
  // Fern inlines every `<Markdown src>`, even inside a fenced block, so a shown
  // include tag would turn into the included file. Write its `<` as a
  // <Template> variable instead: Fern's code block (and its copy button) puts
  // the `<` back. The spaces keep Fern's snippet-property check off `lt`.
  // ponytail: <Template> is an undocumented Fern component; if Fern drops it,
  // readers see `{{ lt }}Markdown` and this needs another escape.
  return `<Template data={{ lt: "<" }}>\n\n${block.replace(/<Markdown(?=\s)/g, "{{ lt }}Markdown")}\n\n</Template>`;
}
const FERN_INCLUDE = /<Markdown\s/;

/** Renders mode tabs, each holding format tabs of titled fenced blocks. */
function renderVariants(files) {
  const lines = ["{/* Generated by docs/.scripts/buildDocsAsTestsSnippets.js. Don't edit. */}", "", "<Tabs>"];
  for (const [mode, modeTitle] of MODES) {
    const variants = FORMATS.map(([ext, title, language]) => ({
      title,
      language,
      file: files.find((f) => f.name.split(".")[0] === mode && f.name.split(".").pop() === ext),
    })).filter((v) => v.file);
    if (!variants.length) continue;
    lines.push(`  <Tab title="${modeTitle}">`, "    <Tabs>");
    for (const v of variants) {
      lines.push(`      <Tab title="${v.title}">`, "", fence(v.file.name, v.language, v.file.content), "", "      </Tab>");
    }
    lines.push("    </Tabs>", "  </Tab>");
  }
  lines.push("</Tabs>", "");
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const dir of fs.readdirSync(examplesDir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith("."))) {
    const exampleDir = path.join(examplesDir, dir.name);
    const files = fs
      .readdirSync(exampleDir)
      .filter((name) => /^(prose|detected|inline|standalone)\./.test(name))
      .map((name) => ({ name, content: fs.readFileSync(path.join(exampleDir, name), "utf8").replace(/\r\n/g, "\n") }));
    const outFile = path.join(pagesDir, dir.name, OUTPUT);
    const rendered = renderVariants(files);
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === rendered) continue;
    if (check) stale.push(path.relative(pagesDir, outFile));
    else {
      fs.mkdirSync(path.dirname(outFile), { recursive: true });
      fs.writeFileSync(outFile, rendered);
    }
  }
  if (stale.length) {
    console.error(`Stale snippets (run npm run docs:build-docs-as-tests):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
}

if (require.main === module) main();

module.exports = { renderVariants };
